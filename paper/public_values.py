#!/usr/bin/env python3
"""Write data/public_values.tex and table_public.tex from the DGX public-validation evaluation.

    python public_values.py            # from the repo's evaluation.json (refreshes the local copy)
    python public_values.py --check    # verify the committed outputs
    python public_values.py --from-json  # re-render from data/public_evaluation.json (no repo access)

Source: data/public/walmart-amazon/runs/product-v1-dgx/test/evaluation.json, written by
src/public/walmart_amazon_dgx.py evaluate with the released scorer (walmart_amazon.py).
A copy is kept at data/public_evaluation.json so the paper folder stays self-contained; it
holds only aggregates over the public Walmart-Amazon release (no merchant data). No inference.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parents[1] / "data/public/walmart-amazon/runs/product-v1-dgx/test/evaluation.json"
LOCAL = HERE / "data/public_evaluation.json"
ROWS = (("dual_086_080", r"Pair $(0.86, 0.80)$", "Pair"), ("gemma_086_080", "Gemma 31B alone", "Gemma"),
        ("muse_086_080", "Muse 30B alone", "Muse"), ("dual_080_080", r"Pair $(0.80, 0.80)$", "PairEighty"),
        ("dual_086_086", r"Pair $(0.86, 0.86)$", "PairEightySix"))


def pct(x, nd=2):
    return f"{100 * x:.{nd}f}"


def signed(x, nd=2):
    return f"{100 * x:+.{nd}f}".replace("-", "$-$")


def interval(lo, hi, nd=1):
    return f"[{100 * lo:.{nd}f}, {100 * hi:.{nd}f}]".replace("-", "$-$")


def thousands(n):
    return f"{n:,}".replace(",", "{,}")


def render(ev):
    pol, tex = ev["policies"], ["% GENERATED by public_values.py; do not edit."]

    def macro(name, value):
        tex.append(r"\newcommand{\vPub" + name + "}{" + value + "}")

    macro("N", thousands(ev["n"]))
    macro("Matchable", str(ev["retrieval"]["catalog_matchable_queries"]))
    macro("NoMatch", str(ev["retrieval"]["no_catalog_match_queries"]))
    macro("RetrievalMiss", str(ev["retrieval"]["retrieval_miss_queries"]))
    for key, _, stem in ROWS:
        p = pol[key]
        macro(stem + "Retained", thousands(p["counts"]["positive"] + p["counts"]["negative"]))
        macro(stem + "Pos", str(p["counts"]["positive"]))
        macro(stem + "Neg", str(p["counts"]["negative"]))
        macro(stem + "PosPurity", pct(p["positive"]["rate"]))
        macro(stem + "NegPurity", pct(p["negative"]["rate"]))
        macro(stem + "Purity", pct(p["total"]["rate"]))
        macro(stem + "PurityCi", interval(*p["total"]["wilson95"]))
        macro(stem + "Coverage", pct(p["coverage"], 1))
    gains = ev["primary_minus_baseline_purity"]
    for key, stem in (("gemma_086_080", "Gemma"), ("muse_086_080", "Muse")):
        for pol_key, suffix in (("total", ""), ("positive", "Pos"), ("negative", "Neg")):
            g = gains[key][pol_key]
            macro(f"PairMinus{stem}{suffix}", signed(g["difference"]))
            macro(f"PairMinus{stem}{suffix}Ci", interval(*g["paired_bootstrap95"], nd=2))
    for key, stem in (("dual_086_086", "PairEightySix"), ("dual_080_080", "PairEighty")):
        macro(f"PairMinus{stem}", signed(gains[key]["total"]["difference"]))
    for j, stem in (("gemma", "Gemma"), ("muse", "Muse")):
        macro(stem + "F", pct(ev["judges"][j]["f0_5"]))
        macro(stem + "Failed", str(ev["operational"][j]["failed_attempts"]))
    se = ev["shared_errors_at_080"]
    macro("BothWrong", str(se["both_wrong"]))
    macro("GemmaWrong", str(se["gemma_wrong"]))
    macro("MuseWrong", str(se["muse_wrong"]))

    table = [r"% GENERATED by public_values.py; do not edit.", r"\begin{table}[t]", r"\centering\scriptsize",
             r"\setlength{\tabcolsep}{3pt}",
             r"\caption{Public validation: curation on \vPubN{} reserved Walmart--Amazon test queries with the bf16 pair on DGX Spark, scored against the released reference links. Cells are retained labels (purity, \%); coverage is retained queries / \vPubN. Policies retain different subsets, so this is not a matched-coverage comparison.}",
             r"\label{tab:public}", r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
             r"Policy & Positives & Negatives & Purity (\%) & Cov.\ (\%) \\", r"\midrule"]
    for i, (key, label, _) in enumerate(ROWS):
        p = pol[key]
        if i == 3:
            table.append(r"\midrule")
        table.append(" & ".join([label, f"{p['counts']['positive']} ({pct(p['positive']['rate'])})",
                                 f"{p['counts']['negative']} ({pct(p['negative']['rate'])})",
                                 pct(p["total"]["rate"]), pct(p["coverage"], 1)]) + r" \\")
    table.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    return {"data/public_values.tex": "\n".join(tex) + "\n", "table_public.tex": "\n".join(table) + "\n"}


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--from-json", action="store_true", help="use data/public_evaluation.json only")
    a = ap.parse_args()
    if a.from_json or not SOURCE.exists():
        ev = json.loads(LOCAL.read_text())
    else:
        ev = json.loads(SOURCE.read_text())
        if not a.check:
            LOCAL.write_text(json.dumps(ev, indent=1) + "\n")
    if ev["n"] != 1000 or any(ev["operational"][j]["attempts"] != 1000 for j in ("gemma", "muse")):
        raise SystemExit("public evaluation is not the complete 1,000-query test; not writing")
    for name, content in render(ev).items():
        path = HERE / name
        if a.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"stale or missing: {name}")
        else:
            path.write_text(content)
    print("PASS: public validation " + ("matches saved outputs" if a.check else "regenerated"))
